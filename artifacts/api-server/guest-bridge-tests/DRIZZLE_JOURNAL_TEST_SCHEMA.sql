-- ONLY for disposable isolated PGlite/PG integration validation.
-- Do not apply to any deployed IAttom database.
CREATE TABLE users(
 clerk_id text PRIMARY KEY,email text NOT NULL,role text NOT NULL DEFAULT 'user',
 plan text NOT NULL DEFAULT 'free',credits integer NOT NULL DEFAULT 0,
 stripe_customer_id text,stripe_subscription_id text,
 stripe_subscription_status text
);
CREATE TABLE credits_transactions(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clerk_user_id text NOT NULL,amount integer NOT NULL,type text NOT NULL,
 balance_type text NOT NULL,stripe_session_id text
);
CREATE TABLE commercial_guest_claims (
 checkout_session_id text PRIMARY KEY,
 stripe_subscription_id text NOT NULL UNIQUE,
 stripe_customer_id text NOT NULL,
 stripe_invoice_id text NOT NULL,
 registration_id text NOT NULL,
 price_id text NOT NULL,
 commercial_plan text NOT NULL CHECK(commercial_plan IN ('START','PREMIUM','PRO')),
 checkout_created_at bigint NOT NULL,
 pre_registration_issued_at bigint NOT NULL,
 pre_registration_proof text NOT NULL,
 plan_key text NOT NULL CHECK(plan_key IN ('pro','business','agency')),
 general_credit_amount integer NOT NULL CHECK(general_credit_amount>0),
 billing_period_start bigint NOT NULL,
 billing_period_end bigint NOT NULL,
 clerk_user_id text,
 status text NOT NULL DEFAULT 'PAID_UNLINKED' CHECK(status IN
  ('PAID_UNLINKED','READY','PROCESSING','RETRYABLE','COMPLETED','REVIEW')),
 lease_token text,lease_expires_at timestamptz,
 last_error text,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(billing_period_end>billing_period_start),
 CHECK((status='PAID_UNLINKED' AND clerk_user_id IS NULL) OR status<>'PAID_UNLINKED')
);
CREATE INDEX ON commercial_guest_claims(clerk_user_id);
